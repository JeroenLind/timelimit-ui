#!/usr/bin/env python3
"""Generate the action wire-format reference from the timelimit-server sources.

Usage: gen_actions.py <path-to-timelimit-server>/src > actions-reference.md

Reads action/serialization/{parentaction,childaction,applogicaction}.ts to learn
which `Serialized*` interface belongs to which outer action type, then extracts
each interface (its `type` literal and fields) from src/**/*.ts.
Only reads files; the server checkout is never modified.
"""

import re
import sys
from pathlib import Path

src = Path(sys.argv[1])

IFACE = re.compile(
    r"export interface (\w+)(?:<[^>]*>)?\s*(?:extends [^{]+)?\{(.*?)^\}", re.S | re.M
)


def esc(text: str) -> str:
    return text.replace("|", "\\|")


def strip_comments(body: str) -> str:
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    return body


def join_nested(body: str) -> str:
    """Join multi-line inline object types (`items: Array<{ ... }>`) into one line."""
    out, buf, depth = [], "", 0
    for raw in body.splitlines():
        line = raw.split("//", 1)[0].rstrip() if depth else raw
        if depth == 0 and ("{" not in raw or raw.count("{") == raw.count("}")):
            out.append(raw)
            continue
        buf = (
            (
                buf
                + ("" if buf.rstrip().endswith("{") else ";")
                + " "
                + line.strip().rstrip(";,")
            )
            if buf
            else raw.rstrip()
        )
        depth = buf.count("{") - buf.count("}")
        if depth <= 0:
            out.append(re.sub(r"\s+", " ", buf))
            buf, depth = "", 0
    if buf:
        out.append(re.sub(r"\s+", " ", buf))
    text = "\n".join(out)
    text = re.sub(r";(\s*;)+", ";", text)
    return re.sub(r";\s*}", " }", text)


def parse_fields(body: str):
    body = join_nested(strip_comments(body))
    fields = []
    for raw in body.splitlines():
        line = raw.strip()
        if not line or line.startswith("//"):
            continue
        comment = ""
        if "//" in line:
            line, comment = line.split("//", 1)
            line, comment = line.strip(), comment.strip()
        line = line.rstrip(";,").strip()
        m = re.match(r"(?:readonly\s+)?(\w+)(\??):\s*(.+)$", line)
        if m:
            name, opt, typ = m.groups()
            fields.append((name, bool(opt), typ.strip(), comment))
    return fields


# 1. every interface in the source tree
interfaces = {}
for p in sorted(src.rglob("*.ts")):
    text = p.read_text(encoding="utf-8")
    for m in IFACE.finditer(text):
        interfaces[m.group(1)] = (str(p.relative_to(src)), parse_fields(m.group(2)))


# 2. which interfaces belong to which outer group
def union_members(file: Path, type_name: str):
    text = file.read_text(encoding="utf-8")
    m = re.search(
        r"export type " + type_name + r"\s*=(.*?)(?:\n\n|\nexport )", text, re.S
    )
    if not m:
        return []
    return re.findall(
        r"\b(Serializ\w+|Serialiez\w+|Serialiiz\w+|SerialiezdTried\w+|Serial\w+)\b",
        m.group(1),
    )


ser = src / "action" / "serialization"
groups = [
    ("parent", "SerializedParentAction", ser / "parentaction.ts"),
    ("child", "SerializedChildAction", ser / "childaction.ts"),
    ("appLogic", "SerializedAppLogicAction", ser / "applogicaction.ts"),
]

out = []
referenced = set()
print(
    "<!-- GENERATED by docs/protocol/gen_actions.py from timelimit-server sources. Do not edit by hand. -->\n"
)
for outer, tname, f in groups:
    names = union_members(f, tname)
    rows = []
    for n in names:
        if n not in interfaces:
            print(f"WARNING: {n} in {tname} but no interface found", file=sys.stderr)
            continue
        path, fields = interfaces[n]
        typ = next((t for (fn, _o, t, _c) in fields if fn == "type"), None)
        rows.append(
            (
                typ.strip("'\" ") if typ else "?",
                n,
                path,
                [x for x in fields if x[0] != "type"],
            )
        )
    rows.sort(key=lambda r: r[0])
    print(f"## Outer type `{outer}` ({len(rows)} actions)\n")
    for typ, n, path, fields in rows:
        print(f"### `{typ}`\n")
        print(f"Source: `src/{path}` (interface `{n}`)\n")
        if fields:
            print("| Field | Type | Required | Note |")
            print("|---|---|---|---|")
            for fn, opt, t, c in fields:
                for ref in re.findall(r"\b([A-Z]\w+)\b", t):
                    referenced.add(ref)
                print(f"| `{fn}` | `{esc(t)}` | {'no' if opt else 'yes'} | {esc(c)} |")
        else:
            print("No fields besides `type`.")
        print()

# 3. shared types referenced by fields
shared = sorted(
    r for r in referenced if r in interfaces and not r.startswith("Serialized")
)
shared += sorted(
    r
    for r in referenced
    if r in interfaces
    and r.startswith("Serialized")
    and not any(r == n for _, _, _ in [] for n in [])
)
seen = set()
print("## Shared types used in action fields\n")
for r in shared:
    if r in seen:
        continue
    seen.add(r)
    path, fields = interfaces[r]
    if any(fn == "type" and t.strip("'\" ").isupper() for fn, _o, t, _c in fields):
        continue  # a top-level action, already listed above
    print(f"### `{r}`\n")
    print(f"Source: `src/{path}`\n")
    print("| Field | Type | Required | Note |")
    print("|---|---|---|---|")
    for fn, opt, t, c in fields:
        print(f"| `{fn}` | `{esc(t)}` | {'no' if opt else 'yes'} | {esc(c)} |")
    print()
